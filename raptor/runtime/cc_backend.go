// cc_backend.go implements the Goose-inspired native C11 + AVX2 + 8-bit LSD Radix Sort
// compiler (`--cc` / `-cc`), translating Raptor ASTs into standalone native binaries
// backed by a 16 MB pointerless bump arena via GCC, Clang, or `zig cc`.
package raptor

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	goruntime "runtime"
	"strconv"
	"strings"
)

// resolveNativeCCompiler locates GCC, Clang, or `zig cc` on the host machine for the Goose-style C11 backend.
func resolveNativeCCompiler() (string, []string, error) {
	if cc := strings.TrimSpace(os.Getenv("RAPTOR_CC")); cc != "" {
		fields := strings.Fields(cc)
		if len(fields) > 0 {
			if p, err := exec.LookPath(fields[0]); err == nil {
				return p, fields[1:], nil
			}
			if _, err := os.Stat(fields[0]); err == nil {
				return fields[0], fields[1:], nil
			}
		}
	}
	for _, name := range []string{"gcc", "clang", "cc"} {
		if p, err := exec.LookPath(name); err == nil {
			return p, nil, nil
		}
	}
	if zigPath, err := exec.LookPath("zig"); err == nil {
		return zigPath, []string{"cc"}, nil
	}
	if goruntime.GOOS == "windows" {
		for _, p := range []string{
			`C:\msys64\ucrt64\bin\gcc.exe`,
			`C:\msys64\mingw64\bin\gcc.exe`,
			`C:\msys64\clang64\bin\clang.exe`,
		} {
			if _, err := os.Stat(p); err == nil {
				return p, nil, nil
			}
		}
	}
	return "", nil, fmt.Errorf("no C compiler (gcc/clang/zig) found; set RAPTOR_CC or add gcc/zig to PATH")
}

// FindNativeCCompiler locates GCC, Clang, or Zig on the host machine for the Goose-style C11 backend.
func FindNativeCCompiler() (string, error) {
	bin, _, err := resolveNativeCCompiler()
	return bin, err
}

// CompileScriptToNativeExe transpiles Raptor source to Goose-style arena-backed C11 with AVX2/radix-sort
// and compiles it to a standalone native binary via gcc/clang/zig cc -O3 -march=native.
func CompileScriptToNativeExe(source, outPath string) error {
	prog, err := ParseProgram(source)
	if err != nil {
		return fmt.Errorf("parse error: %w", err)
	}
	cSrc, err := EmitNativeC11(prog)
	if err != nil {
		return err
	}
	if strings.HasSuffix(strings.ToLower(outPath), ".c") {
		return os.WriteFile(outPath, []byte(cSrc), 0644)
	}
	ccBin, ccPrefixArgs, err := resolveNativeCCompiler()
	if err != nil {
		return err
	}
	tmpDir := os.TempDir()
	sum := sha256.Sum256([]byte(cSrc))
	cFile := filepath.Join(tmpDir, "raptor_gen_"+hex.EncodeToString(sum[:8])+".c")
	if err := os.WriteFile(cFile, []byte(cSrc), 0644); err != nil {
		return err
	}
	defer os.Remove(cFile)

	args := append([]string{}, ccPrefixArgs...)
	args = append(args, "-O3", "-march=native", "-std=c11", cFile, "-o", outPath)
	if goruntime.GOOS != "windows" {
		args = append(args, "-lm")
	}
	cmd := exec.Command(ccBin, args...)
	cmd.Env = append(os.Environ(), "PATH="+os.Getenv("PATH")+string(os.PathListSeparator)+filepath.Dir(ccBin))
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("cc build failed (%s): %w\n%s", ccBin, err, stderr.String())
	}
	return nil
}

func (in *Interp) evalCC(source string) (*Value, error) {
	prog, err := ParseProgram(source)
	if err != nil {
		return nil, err
	}
	cSrc, err := EmitNativeC11(prog)
	if err != nil {
		// Seamless fallback to Go interpreter for dynamic features outside static C11 subset
		return in.EvalProgram(prog, in.GlobalEnv)
	}
	cacheDir := filepath.Join(os.TempDir(), "raptor_cc_cache")
	_ = os.MkdirAll(cacheDir, 0755)
	sum := sha256.Sum256([]byte(cSrc))
	ext := ""
	if goruntime.GOOS == "windows" {
		ext = ".exe"
	}
	exePath := filepath.Join(cacheDir, "rp_"+hex.EncodeToString(sum[:12])+ext)
	if _, statErr := os.Stat(exePath); statErr != nil {
		if err := CompileScriptToNativeExe(source, exePath); err != nil {
			return in.EvalProgram(prog, in.GlobalEnv)
		}
	}
	cmd := exec.Command(exePath)
	if in.Stdout == nil || in.Stdout == os.Stdout {
		cmd.Stdout = os.Stdout
		cmd.Stderr = os.Stderr
		if err := cmd.Run(); err != nil {
			return nil, err
		}
		return NilValue(), nil
	}
	var outBuf bytes.Buffer
	cmd.Stdout = &outBuf
	cmd.Stderr = in.Stderr
	if err := cmd.Run(); err != nil {
		return nil, err
	}
	in.Stdout.Write(outBuf.Bytes())
	return NilValue(), nil
}

type ccType uint8

const (
	ctUnknown ccType = iota
	ctInt
	ctFloat
	ctBool
	ctStr
	ctIntVec
	ctIntMap
)

type ccEmitter struct {
	vars     map[string]ccType
	subTypes map[string]ccType
	subs     []*SubDeclStmt
	body     strings.Builder
	indent   int
}

const c11RuntimePreamble = `/* Generated by Raptor Native C11 Backend (Goose Bump-Arena + Columnar SIMD + Radix Sort) */
#include <stdio.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <inttypes.h>
#if defined(__x86_64__) || defined(_M_X64)
#include <immintrin.h>
#endif

/* 1. Goose-Style Contiguous Bump-Pointer Data-Stack Arena (Zero GC, Zero free() Overhead) */
static uint8_t rp_static_slab[16 * 1024 * 1024];
static size_t  rp_slab_off = 0;

static inline void* rp_arena_alloc(size_t bytes) {
    bytes = (bytes + 31u) & ~31u;
    if (__builtin_expect(rp_slab_off + bytes <= sizeof(rp_static_slab), 1)) {
        void *p = &rp_static_slab[rp_slab_off];
        rp_slab_off += bytes;
        return p;
    }
    return malloc(bytes);
}

/* 2. Length-Tracked Inline String Slice (O(1) length, word-aligned eq, amortized arena append) */
typedef struct {
    char  *ptr;
    size_t len;
    size_t cap;
} RpStr;

static inline RpStr rp_str_lit(const char *s, size_t len) {
    RpStr r = { (char*)s, len, 0 };
    return r;
}

static inline bool rp_str_eq(RpStr a, RpStr b) {
    if (a.len != b.len) return false;
    if (a.ptr == b.ptr || a.len == 0) return true;
    return memcmp(a.ptr, b.ptr, a.len) == 0;
}

static inline int rp_str_cmp(RpStr a, RpStr b) {
    size_t m = a.len < b.len ? a.len : b.len;
    int c = m ? memcmp(a.ptr, b.ptr, m) : 0;
    if (c != 0) return c;
    return (a.len > b.len) - (a.len < b.len);
}

static inline RpStr rp_str_concat(RpStr a, RpStr b) {
    size_t n = a.len + b.len;
    size_t cap = n < 64 ? 64 : n * 2;
    char *buf = (char*)rp_arena_alloc(cap + 1);
    if (a.len) memcpy(buf, a.ptr, a.len);
    if (b.len) memcpy(buf + a.len, b.ptr, b.len);
    buf[n] = '\0';
    RpStr r = { buf, n, cap };
    return r;
}

static inline void rp_str_append(RpStr *dst, RpStr suf) {
    if (suf.len == 0) return;
    if (__builtin_expect(dst->cap >= dst->len + suf.len, 1)) {
        memcpy(dst->ptr + dst->len, suf.ptr, suf.len);
        dst->len += suf.len;
        dst->ptr[dst->len] = '\0';
        return;
    }
    size_t need = dst->len + suf.len;
    size_t new_cap = dst->cap ? dst->cap * 2 : 128;
    while (new_cap < need) new_cap *= 2;
    char *nb = (char*)rp_arena_alloc(new_cap + 1);
    if (dst->len) memcpy(nb, dst->ptr, dst->len);
    memcpy(nb + dst->len, suf.ptr, suf.len);
    dst->len = need;
    nb[need] = '\0';
    dst->ptr = nb;
    dst->cap = new_cap;
}

/* 3. Columnar Int64 Vector + AVX2 Sum + O(n) Counting / 16-Bit LSD Radix Sort */
typedef struct {
    int64_t *data;
    size_t   len;
    size_t   cap;
} RpIntVec;

static inline RpIntVec rp_ivec_new(size_t init_cap) {
    if (init_cap < 64) init_cap = 64;
    RpIntVec v = { (int64_t*)rp_arena_alloc(init_cap * sizeof(int64_t)), 0, init_cap };
    return v;
}

static inline void rp_ivec_push(RpIntVec *v, int64_t x) {
    if (__builtin_expect(v->len == v->cap, 0)) {
        size_t nc = v->cap ? v->cap * 2 : 1024;
        int64_t *nd = (int64_t*)rp_arena_alloc(nc * sizeof(int64_t));
        if (v->len) memcpy(nd, v->data, v->len * sizeof(int64_t));
        v->data = nd;
        v->cap = nc;
    }
    v->data[v->len++] = x;
}

static inline int64_t rp_ivec_sum(RpIntVec v) {
    size_t i = 0, n = v.len;
    int64_t sum = 0;
#if defined(__AVX2__)
    __m256i acc0 = _mm256_setzero_si256();
    __m256i acc1 = _mm256_setzero_si256();
    for (; i + 8 <= n; i += 8) {
        acc0 = _mm256_add_epi64(acc0, _mm256_loadu_si256((const __m256i*)(v.data + i)));
        acc1 = _mm256_add_epi64(acc1, _mm256_loadu_si256((const __m256i*)(v.data + i + 4)));
    }
    acc0 = _mm256_add_epi64(acc0, acc1);
    int64_t lanes[4];
    _mm256_storeu_si256((__m256i*)lanes, acc0);
    sum = lanes[0] + lanes[1] + lanes[2] + lanes[3];
#endif
    for (; i < n; i++) sum += v.data[i];
    return sum;
}

static RpIntVec rp_ivec_sort(RpIntVec src_vec) {
    size_t n = src_vec.len;
    RpIntVec out = { (int64_t*)rp_arena_alloc((n ? n : 1) * sizeof(int64_t)), n, n };
    if (n == 0) return out;
    memcpy(out.data, src_vec.data, n * sizeof(int64_t));
    if (n < 2) return out;

    int64_t min_v = out.data[0], max_v = out.data[0];
    bool already = true;
    for (size_t i = 1; i < n; i++) {
        int64_t x = out.data[i];
        if (x < out.data[i - 1]) already = false;
        if (x < min_v) min_v = x;
        else if (x > max_v) max_v = x;
    }
    if (already) return out;

    /* O(n) L2-resident Counting Sort for bounded integer domains */
    if ((uint64_t)(max_v - min_v) <= 262144ULL) {
        size_t span = (size_t)(max_v - min_v) + 1;
        uint32_t *counts = (uint32_t*)rp_arena_alloc(span * sizeof(uint32_t));
        memset(counts, 0, span * sizeof(uint32_t));
        for (size_t i = 0; i < n; i++) {
            counts[(size_t)(out.data[i] - min_v)]++;
        }
        size_t pos = 0;
        for (size_t b = 0; b < span; b++) {
            uint32_t c = counts[b];
            int64_t val = min_v + (int64_t)b;
            while (c--) out.data[pos++] = val;
        }
        return out;
    }

    /* 4-Pass 16-bit LSD Radix Sort for arbitrary 64-bit integers */
    uint64_t *a = (uint64_t*)out.data;
    uint64_t *b = (uint64_t*)rp_arena_alloc(n * sizeof(uint64_t));
    const uint64_t sign_bit = 1ULL << 63;
    for (size_t i = 0; i < n; i++) a[i] ^= sign_bit;
    uint32_t hist[65536];
    for (unsigned shift = 0; shift < 64; shift += 16) {
        memset(hist, 0, sizeof(hist));
        for (size_t i = 0; i < n; i++) hist[(a[i] >> shift) & 0xFFFFu]++;
        bool trivial = false;
        uint32_t sum = 0;
        for (size_t k = 0; k < 65536; k++) {
            uint32_t c = hist[k];
            if (c == n) { trivial = true; break; }
            hist[k] = sum;
            sum += c;
        }
        if (trivial) continue;
        for (size_t i = 0; i < n; i++) {
            uint32_t idx = (uint32_t)((a[i] >> shift) & 0xFFFFu);
            b[hist[idx]++] = a[i];
        }
        uint64_t *tmp = a; a = b; b = tmp;
    }
    if ((void*)a != (void*)out.data) memcpy(out.data, a, n * sizeof(uint64_t));
    for (size_t i = 0; i < n; i++) out.data[i] = (int64_t)((uint64_t)out.data[i] ^ sign_bit);
    return out;
}

/* 4. Flat L1-Cache Open-Addressing Integer Hash Table */
typedef struct {
    int64_t *keys;
    int64_t *vals;
    uint8_t *used;
    size_t   mask;
    size_t   len;
} RpIntMap;

static inline RpIntMap rp_imap_new(size_t cap_pow2) {
    if (cap_pow2 < 2048) cap_pow2 = 2048;
    RpIntMap m;
    m.keys = (int64_t*)rp_arena_alloc(cap_pow2 * sizeof(int64_t));
    m.vals = (int64_t*)rp_arena_alloc(cap_pow2 * sizeof(int64_t));
    m.used = (uint8_t*)rp_arena_alloc(cap_pow2);
    memset(m.used, 0, cap_pow2);
    m.mask = cap_pow2 - 1;
    m.len  = 0;
    return m;
}

static inline int64_t rp_imap_get(const RpIntMap *m, int64_t k) {
    size_t idx = (size_t)(((uint64_t)k * 11400714819323198485ULL) >> 52) & m->mask;
    while (m->used[idx]) {
        if (m->keys[idx] == k) return m->vals[idx];
        idx = (idx + 1) & m->mask;
    }
    return 0;
}

static inline void rp_imap_set(RpIntMap *m, int64_t k, int64_t v) {
    size_t idx = (size_t)(((uint64_t)k * 11400714819323198485ULL) >> 52) & m->mask;
    while (m->used[idx]) {
        if (m->keys[idx] == k) { m->vals[idx] = v; return; }
        idx = (idx + 1) & m->mask;
    }
    m->used[idx] = 1;
    m->keys[idx] = k;
    m->vals[idx] = v;
    m->len++;
}
`

// EmitNativeC11 transpiles a Raptor AST Program to freestanding C11 source code.
func EmitNativeC11(prog *Program) (string, error) {
	if prog == nil {
		return "", fmt.Errorf("cc backend: nil program")
	}
	em := &ccEmitter{
		vars:     make(map[string]ccType),
		subTypes: make(map[string]ccType),
	}

	var mainStmts []Stmt
	for _, st := range prog.Stmts {
		if sd, ok := st.(*SubDeclStmt); ok {
			if sd.IsMulti {
				return "", fmt.Errorf("cc backend: multi sub not supported in static C11 mode")
			}
			em.subs = append(em.subs, sd)
			em.subTypes[sd.Name] = ctInt
		} else {
			mainStmts = append(mainStmts, st)
		}
	}

	var out strings.Builder
	out.WriteString(c11RuntimePreamble)
	out.WriteString("\n")

	// Forward declarations for subroutines
	for _, sd := range em.subs {
		sig, err := em.formatSubSig(sd)
		if err != nil {
			return "", err
		}
		out.WriteString(sig + ";\n")
	}
	if len(em.subs) > 0 {
		out.WriteString("\n")
	}

	// Emit subroutine definitions
	for _, sd := range em.subs {
		subEm := &ccEmitter{
			vars:     make(map[string]ccType),
			subTypes: em.subTypes,
			indent:   1,
		}
		for _, p := range sd.Params {
			if p.IsSlurpy || len(p.DestructArr) > 0 || len(p.DestructHash) > 0 || p.Where != nil {
				return "", fmt.Errorf("cc backend: complex parameter on %s", sd.Name)
			}
			subEm.vars[p.Name] = ctInt
		}
		sig, err := em.formatSubSig(sd)
		if err != nil {
			return "", err
		}
		if err := subEm.emitStmts(sd.Body.Stmts); err != nil {
			return "", err
		}
		out.WriteString(sig + " {\n")
		out.WriteString(subEm.body.String())
		out.WriteString("    return 0;\n}\n\n")
	}

	// Emit main()
	em.indent = 1
	if err := em.emitStmts(mainStmts); err != nil {
		return "", err
	}
	out.WriteString("int main(void) {\n")
	out.WriteString(em.body.String())
	out.WriteString("    return 0;\n}\n")
	return out.String(), nil
}

func cIdent(raw string) string {
	var b strings.Builder
	b.WriteString("v_")
	for _, r := range raw {
		switch r {
		case '$':
			b.WriteString("s_")
		case '@':
			b.WriteString("a_")
		case '%':
			b.WriteString("h_")
		default:
			if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_' {
				b.WriteRune(r)
			} else {
				fmt.Fprintf(&b, "_x%x_", r)
			}
		}
	}
	return b.String()
}

func cTypeName(t ccType) string {
	switch t {
	case ctFloat:
		return "double"
	case ctBool:
		return "bool"
	case ctStr:
		return "RpStr"
	case ctIntVec:
		return "RpIntVec"
	case ctIntMap:
		return "RpIntMap"
	default:
		return "int64_t"
	}
}

func (e *ccEmitter) formatSubSig(sd *SubDeclStmt) (string, error) {
	var ps []string
	for _, p := range sd.Params {
		ps = append(ps, "int64_t "+cIdent(p.Name))
	}
	paramStr := "void"
	if len(ps) > 0 {
		paramStr = strings.Join(ps, ", ")
	}
	return fmt.Sprintf("static int64_t rp_sub_%s(%s)", cIdent(sd.Name), paramStr), nil
}

func (e *ccEmitter) pad() string {
	return strings.Repeat("    ", e.indent)
}

func (e *ccEmitter) inferType(ex Expr) ccType {
	if ex == nil {
		return ctInt
	}
	switch x := ex.(type) {
	case *LiteralExpr:
		switch x.Type {
		case TokInt:
			return ctInt
		case TokFloat:
			return ctFloat
		case TokString:
			return ctStr
		case TokIdent:
			s := x.Value.(string)
			if s == "True" || s == "true" || s == "False" || s == "false" {
				return ctBool
			}
			return ctStr
		}
	case *InterpStringExpr:
		return ctStr
	case *VarExpr:
		if t, ok := e.vars[x.Name]; ok {
			return t
		}
		if strings.HasPrefix(x.Name, "@") {
			return ctIntVec
		}
		if strings.HasPrefix(x.Name, "%") {
			return ctIntMap
		}
		return ctInt
	case *ArrayLiteralExpr:
		return ctIntVec
	case *HashLiteralExpr:
		return ctIntMap
	case *BinaryExpr:
		switch x.Op {
		case "~":
			return ctStr
		case "/":
			return ctFloat
		case "==", "!=", "<", "<=", ">", ">=", "eq", "ne", "lt", "gt", "le", "ge", "%%", "&&", "||", "and", "or":
			return ctBool
		case "+", "-", "*":
			if e.inferType(x.Left) == ctFloat || e.inferType(x.Right) == ctFloat {
				return ctFloat
			}
			return ctInt
		}
		return ctInt
	case *MethodCallExpr:
		switch x.Method {
		case "sort":
			return ctIntVec
		case "chars", "length", "elems", "sum":
			return ctInt
		}
	case *CallExpr:
		if cv, ok := x.Callee.(*VarExpr); ok {
			switch cv.Name {
			case "sort":
				return ctIntVec
			case "chars", "length", "elems", "sum", "∑", "int":
				return ctInt
			case "sqrt", "sin", "cos", "log", "exp", "num":
				return ctFloat
			}
			if rt, ok := e.subTypes[cv.Name]; ok {
				return rt
			}
		}
	}
	return ctInt
}

func (e *ccEmitter) emitStmts(stmts []Stmt) error {
	for _, st := range stmts {
		if err := e.emitStmt(st); err != nil {
			return err
		}
	}
	return nil
}

func (e *ccEmitter) emitStmt(st Stmt) error {
	switch s := st.(type) {
	case *VarDeclStmt:
		if s.Scope != "my" || s.Where != nil {
			return fmt.Errorf("cc backend: unsupported var decl %s", s.Name)
		}
		var vt ccType
		if strings.HasPrefix(s.Name, "@") {
			vt = ctIntVec
		} else if strings.HasPrefix(s.Name, "%") {
			vt = ctIntMap
		} else if s.Value != nil {
			vt = e.inferType(s.Value)
		} else {
			vt = ctInt
		}
		e.vars[s.Name] = vt
		cname := cIdent(s.Name)
		if vt == ctIntVec {
			if s.Value == nil {
				fmt.Fprintf(&e.body, "%sRpIntVec %s = rp_ivec_new(64);\n", e.pad(), cname)
				return nil
			}
			if al, ok := s.Value.(*ArrayLiteralExpr); ok && len(al.Elements) == 0 {
				fmt.Fprintf(&e.body, "%sRpIntVec %s = rp_ivec_new(64);\n", e.pad(), cname)
				return nil
			}
			rhs, _, err := e.emitExpr(s.Value)
			if err != nil {
				return err
			}
			fmt.Fprintf(&e.body, "%sRpIntVec %s = %s;\n", e.pad(), cname, rhs)
			return nil
		}
		if vt == ctIntMap {
			fmt.Fprintf(&e.body, "%sRpIntMap %s = rp_imap_new(2048);\n", e.pad(), cname)
			return nil
		}
		if s.Value == nil {
			if vt == ctStr {
				fmt.Fprintf(&e.body, "%sRpStr %s = rp_str_lit(\"\", 0);\n", e.pad(), cname)
			} else {
				fmt.Fprintf(&e.body, "%s%s %s = 0;\n", e.pad(), cTypeName(vt), cname)
			}
			return nil
		}
		rhs, _, err := e.emitExpr(s.Value)
		if err != nil {
			return err
		}
		fmt.Fprintf(&e.body, "%s%s %s = %s;\n", e.pad(), cTypeName(vt), cname, rhs)
		return nil

	case *AssignStmt:
		code, err := e.formatAssign(s)
		if err != nil {
			return err
		}
		fmt.Fprintf(&e.body, "%s%s;\n", e.pad(), code)
		return nil

	case *IfStmt:
		cond, _, err := e.emitCond(s.Condition)
		if err != nil {
			return err
		}
		fmt.Fprintf(&e.body, "%sif (%s) {\n", e.pad(), cond)
		e.indent++
		if err := e.emitStmts(s.ThenBranch.Stmts); err != nil {
			return err
		}
		e.indent--
		for i, ec := range s.ElsifConds {
			ecStr, _, err := e.emitCond(ec)
			if err != nil {
				return err
			}
			fmt.Fprintf(&e.body, "%s} else if (%s) {\n", e.pad(), ecStr)
			e.indent++
			if err := e.emitStmts(s.ElsifThen[i].Stmts); err != nil {
				return err
			}
			e.indent--
		}
		if s.ElseBranch != nil {
			fmt.Fprintf(&e.body, "%s} else {\n", e.pad())
			e.indent++
			if err := e.emitStmts(s.ElseBranch.Stmts); err != nil {
				return err
			}
			e.indent--
		}
		fmt.Fprintf(&e.body, "%s}\n", e.pad())
		return nil

	case *WhileStmt:
		cond, _, err := e.emitCond(s.Condition)
		if err != nil {
			return err
		}
		if s.IsUntil {
			cond = "!(" + cond + ")"
		}
		fmt.Fprintf(&e.body, "%swhile (%s) {\n", e.pad(), cond)
		e.indent++
		if err := e.emitStmts(s.Body.Stmts); err != nil {
			return err
		}
		e.indent--
		fmt.Fprintf(&e.body, "%s}\n", e.pad())
		return nil

	case *LoopStmt:
		initStr := ""
		if s.Init != nil {
			if as, ok := s.Init.(*AssignStmt); ok && as.IsMyDecl {
				ve, okV := as.Target.(*VarExpr)
				if !okV {
					return fmt.Errorf("cc backend: invalid loop init")
				}
				e.vars[ve.Name] = ctInt
				rhs, _, err := e.emitExpr(as.Value)
				if err != nil {
					return err
				}
				initStr = fmt.Sprintf("int64_t %s = %s", cIdent(ve.Name), rhs)
			} else if as, ok := s.Init.(*AssignStmt); ok {
				var err error
				initStr, err = e.formatAssign(as)
				if err != nil {
					return err
				}
			} else {
				var err error
				initStr, _, err = e.emitExpr(s.Init)
				if err != nil {
					return err
				}
			}
		}
		condStr := ""
		if s.Cond != nil {
			var err error
			condStr, _, err = e.emitCond(s.Cond)
			if err != nil {
				return err
			}
		}
		stepStr := ""
		if s.Step != nil {
			if as, ok := s.Step.(*AssignStmt); ok {
				var err error
				stepStr, err = e.formatAssign(as)
				if err != nil {
					return err
				}
			} else {
				var err error
				stepStr, _, err = e.emitExpr(s.Step)
				if err != nil {
					return err
				}
			}
		}
		fmt.Fprintf(&e.body, "%sfor (%s; %s; %s) {\n", e.pad(), initStr, condStr, stepStr)
		e.indent++
		if err := e.emitStmts(s.Body.Stmts); err != nil {
			return err
		}
		e.indent--
		fmt.Fprintf(&e.body, "%s}\n", e.pad())
		return nil

	case *ForStmt:
		if len(s.VarNames) > 0 || s.VarName == "" {
			return fmt.Errorf("cc backend: topic/multi-var for unsupported")
		}
		var startC, endC string
		inclusive := true
		if ue, ok := s.Iterable.(*UnaryExpr); ok && ue.Op == "^" {
			rc, _, err := e.emitExpr(ue.Right)
			if err != nil {
				return err
			}
			startC = "0"
			endC = rc
			inclusive = false
		} else if be, ok := s.Iterable.(*BinaryExpr); ok && (be.Op == ".." || be.Op == "..^") {
			lc, _, err := e.emitExpr(be.Left)
			if err != nil {
				return err
			}
			rc, _, err := e.emitExpr(be.Right)
			if err != nil {
				return err
			}
			startC, endC = lc, rc
			inclusive = be.Op == ".."
		} else {
			return fmt.Errorf("cc backend: non-range for unsupported")
		}
		e.vars[s.VarName] = ctInt
		vn := cIdent(s.VarName)
		cmp := "<="
		if !inclusive {
			cmp = "<"
		}
		fmt.Fprintf(&e.body, "%sfor (int64_t %s = %s; %s %s (%s); %s++) {\n", e.pad(), vn, startC, vn, cmp, endC, vn)
		e.indent++
		if err := e.emitStmts(s.Body.Stmts); err != nil {
			return err
		}
		e.indent--
		fmt.Fprintf(&e.body, "%s}\n", e.pad())
		return nil

	case *ReturnStmt:
		if s.Value == nil {
			fmt.Fprintf(&e.body, "%sreturn 0;\n", e.pad())
			return nil
		}
		rv, _, err := e.emitExpr(s.Value)
		if err != nil {
			return err
		}
		fmt.Fprintf(&e.body, "%sreturn %s;\n", e.pad(), rv)
		return nil

	case *BreakStmt:
		fmt.Fprintf(&e.body, "%sbreak;\n", e.pad())
		return nil

	case *ContinueStmt:
		fmt.Fprintf(&e.body, "%scontinue;\n", e.pad())
		return nil

	case *ExprStmt:
		if ce, ok := s.Expr.(*CallExpr); ok {
			if cv, okV := ce.Callee.(*VarExpr); okV && (cv.Name == "say" || cv.Name == "print") {
				return e.emitPrintCall(ce.Args, cv.Name == "say")
			}
		}
		if as, ok := s.Expr.(*AssignStmt); ok {
			return e.emitStmt(as)
		}
		ex, _, err := e.emitExpr(s.Expr)
		if err != nil {
			return err
		}
		fmt.Fprintf(&e.body, "%s(void)(%s);\n", e.pad(), ex)
		return nil
	}
	return fmt.Errorf("cc backend: unsupported statement %T", st)
}

func (e *ccEmitter) emitPrintCall(args []Expr, newline bool) error {
	var fmtStr strings.Builder
	var cArgs []string
	for _, a := range args {
		code, t, err := e.emitExpr(a)
		if err != nil {
			return err
		}
		switch t {
		case ctInt:
			fmtStr.WriteString("%lld")
			cArgs = append(cArgs, fmt.Sprintf("(long long)(%s)", code))
		case ctFloat:
			fmtStr.WriteString("%.15g")
			cArgs = append(cArgs, code)
		case ctBool:
			fmtStr.WriteString("%s")
			cArgs = append(cArgs, fmt.Sprintf("((%s) ? \"True\" : \"False\")", code))
		case ctStr:
			tp := fmt.Sprintf("_rp_ps_%d", e.body.Len())
			fmt.Fprintf(&e.body, "%sRpStr %s = %s;\n", e.pad(), tp, code)
			fmtStr.WriteString("%.*s")
			cArgs = append(cArgs, fmt.Sprintf("(int)%s.len, %s.ptr", tp, tp))
		default:
			return fmt.Errorf("cc backend: unsupported print arg type")
		}
	}
	if newline {
		fmtStr.WriteString("\\n")
	}
	if len(cArgs) == 0 {
		fmt.Fprintf(&e.body, "%sprintf(\"%s\");\n", e.pad(), fmtStr.String())
	} else {
		fmt.Fprintf(&e.body, "%sprintf(\"%s\", %s);\n", e.pad(), fmtStr.String(), strings.Join(cArgs, ", "))
	}
	return nil
}

func (e *ccEmitter) formatAssign(s *AssignStmt) (string, error) {
	if ha, ok := s.Target.(*HashAccessExpr); ok && s.Op == "=" {
		ve, okV := ha.Hash.(*VarExpr)
		if !okV || e.vars[ve.Name] != ctIntMap {
			return "", fmt.Errorf("cc backend: unsupported hash target")
		}
		kc, _, err := e.emitExpr(ha.Key)
		if err != nil {
			return "", err
		}
		vc, _, err := e.emitExpr(s.Value)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("rp_imap_set(&%s, %s, %s)", cIdent(ve.Name), kc, vc), nil
	}
	if ie, ok := s.Target.(*IndexExpr); ok && s.Op == "=" {
		ve, okV := ie.Array.(*VarExpr)
		if !okV || e.vars[ve.Name] != ctIntVec {
			return "", fmt.Errorf("cc backend: unsupported index target")
		}
		ic, _, err := e.emitExpr(ie.Index)
		if err != nil {
			return "", err
		}
		vc, _, err := e.emitExpr(s.Value)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s.data[%s] = %s", cIdent(ve.Name), ic, vc), nil
	}
	ve, ok := s.Target.(*VarExpr)
	if !ok {
		return "", fmt.Errorf("cc backend: unsupported assignment target %T", s.Target)
	}
	vt, exists := e.vars[ve.Name]
	if !exists {
		vt = e.inferType(s.Value)
		e.vars[ve.Name] = vt
	}
	cn := cIdent(ve.Name)
	if vt == ctStr {
		if s.Op == "~=" {
			suf, _, err := e.emitExpr(s.Value)
			if err != nil {
				return "", err
			}
			return fmt.Sprintf("rp_str_append(&%s, %s)", cn, suf), nil
		}
		if s.Op == "=" {
			if be, okB := s.Value.(*BinaryExpr); okB && be.Op == "~" {
				if lv, okL := be.Left.(*VarExpr); okL && lv.Name == ve.Name {
					suf, _, err := e.emitExpr(be.Right)
					if err != nil {
						return "", err
					}
					return fmt.Sprintf("rp_str_append(&%s, %s)", cn, suf), nil
				}
			}
		}
	}
	vc, _, err := e.emitExpr(s.Value)
	if err != nil {
		return "", err
	}
	switch s.Op {
	case "=", "+=", "-=", "*=", "/=":
		return fmt.Sprintf("%s %s %s", cn, s.Op, vc), nil
	}
	return "", fmt.Errorf("cc backend: unsupported assign op %s", s.Op)
}

func (e *ccEmitter) emitCond(ex Expr) (string, ccType, error) {
	c, t, err := e.emitExpr(ex)
	if err != nil {
		return "", ctUnknown, err
	}
	if t == ctStr {
		return fmt.Sprintf("(%s.len > 0)", c), ctBool, nil
	}
	return c, ctBool, nil
}

func (e *ccEmitter) emitExpr(ex Expr) (string, ccType, error) {
	switch x := ex.(type) {
	case *LiteralExpr:
		switch x.Type {
		case TokInt:
			return fmt.Sprintf("INT64_C(%d)", x.Value.(int64)), ctInt, nil
		case TokFloat:
			return strconv.FormatFloat(x.Value.(float64), 'g', -1, 64), ctFloat, nil
		case TokString:
			s := x.Value.(string)
			return fmt.Sprintf("rp_str_lit(%s, %d)", strconv.QuoteToASCII(s), len(s)), ctStr, nil
		case TokIdent:
			s := x.Value.(string)
			if s == "True" || s == "true" {
				return "true", ctBool, nil
			}
			if s == "False" || s == "false" {
				return "false", ctBool, nil
			}
		}

	case *VarExpr:
		if x.Name == "True" || x.Name == "true" {
			return "true", ctBool, nil
		}
		if x.Name == "False" || x.Name == "false" {
			return "false", ctBool, nil
		}
		vt, ok := e.vars[x.Name]
		if !ok {
			return "", ctUnknown, fmt.Errorf("cc backend: undeclared var %s", x.Name)
		}
		return cIdent(x.Name), vt, nil

	case *IncDecExpr:
		ve, ok := x.Target.(*VarExpr)
		if !ok || e.vars[ve.Name] != ctInt {
			return "", ctUnknown, fmt.Errorf("cc backend: unsupported ++/-- target")
		}
		if x.Post {
			return fmt.Sprintf("(%s%s)", cIdent(ve.Name), x.Op), ctInt, nil
		}
		return fmt.Sprintf("(%s%s)", x.Op, cIdent(ve.Name)), ctInt, nil

	case *UnaryExpr:
		rc, rt, err := e.emitExpr(x.Right)
		if err != nil {
			return "", ctUnknown, err
		}
		switch x.Op {
		case "-":
			return fmt.Sprintf("(-(%s))", rc), rt, nil
		case "+":
			return rc, rt, nil
		case "!", "not":
			return fmt.Sprintf("(!(%s))", rc), ctBool, nil
		}

	case *TernaryExpr:
		cc, _, err := e.emitCond(x.Cond)
		if err != nil {
			return "", ctUnknown, err
		}
		tc, tt, err := e.emitExpr(x.Then)
		if err != nil {
			return "", ctUnknown, err
		}
		fc, _, err := e.emitExpr(x.Else)
		if err != nil {
			return "", ctUnknown, err
		}
		return fmt.Sprintf("((%s) ? (%s) : (%s))", cc, tc, fc), tt, nil

	case *BinaryExpr:
		lc, lt, err := e.emitExpr(x.Left)
		if err != nil {
			return "", ctUnknown, err
		}
		rc, rt, err := e.emitExpr(x.Right)
		if err != nil {
			return "", ctUnknown, err
		}
		switch x.Op {
		case "~":
			if lt != ctStr || rt != ctStr {
				return "", ctUnknown, fmt.Errorf("cc backend: ~ requires strings")
			}
			return fmt.Sprintf("rp_str_concat(%s, %s)", lc, rc), ctStr, nil
		case "eq":
			return fmt.Sprintf("rp_str_eq(%s, %s)", lc, rc), ctBool, nil
		case "ne":
			return fmt.Sprintf("(!rp_str_eq(%s, %s))", lc, rc), ctBool, nil
		case "lt":
			return fmt.Sprintf("(rp_str_cmp(%s, %s) < 0)", lc, rc), ctBool, nil
		case "gt":
			return fmt.Sprintf("(rp_str_cmp(%s, %s) > 0)", lc, rc), ctBool, nil
		case "le":
			return fmt.Sprintf("(rp_str_cmp(%s, %s) <= 0)", lc, rc), ctBool, nil
		case "ge":
			return fmt.Sprintf("(rp_str_cmp(%s, %s) >= 0)", lc, rc), ctBool, nil
		case "%%":
			return fmt.Sprintf("(((%s) %% (%s)) == 0)", lc, rc), ctBool, nil
		case "+", "-", "*":
			resT := ctInt
			if lt == ctFloat || rt == ctFloat {
				resT = ctFloat
			}
			return fmt.Sprintf("((%s) %s (%s))", lc, x.Op, rc), resT, nil
		case "/":
			return fmt.Sprintf("((double)(%s) / (double)(%s))", lc, rc), ctFloat, nil
		case "div":
			return fmt.Sprintf("((%s) / (%s))", lc, rc), ctInt, nil
		case "%", "mod":
			return fmt.Sprintf("((%s) %% (%s))", lc, rc), ctInt, nil
		case "**":
			return fmt.Sprintf("pow((double)(%s), (double)(%s))", lc, rc), ctFloat, nil
		case "+&":
			return fmt.Sprintf("((%s) & (%s))", lc, rc), ctInt, nil
		case "+|":
			return fmt.Sprintf("((%s) | (%s))", lc, rc), ctInt, nil
		case "+^":
			return fmt.Sprintf("((%s) ^ (%s))", lc, rc), ctInt, nil
		case "+<":
			return fmt.Sprintf("((%s) << (%s))", lc, rc), ctInt, nil
		case "+>":
			return fmt.Sprintf("((%s) >> (%s))", lc, rc), ctInt, nil
		case "==", "!=", "<", "<=", ">", ">=":
			return fmt.Sprintf("((%s) %s (%s))", lc, x.Op, rc), ctBool, nil
		case "&&", "and":
			return fmt.Sprintf("((%s) && (%s))", lc, rc), ctBool, nil
		case "||", "or":
			return fmt.Sprintf("((%s) || (%s))", lc, rc), ctBool, nil
		}

	case *IndexExpr:
		ve, ok := x.Array.(*VarExpr)
		if !ok {
			return "", ctUnknown, fmt.Errorf("cc backend: non-var array index")
		}
		// Handle $sorted[0] -> @sorted fallback too
		arrName := ve.Name
		if _, has := e.vars[arrName]; !has && strings.HasPrefix(arrName, "$") {
			if e.vars["@"+arrName[1:]] == ctIntVec {
				arrName = "@" + arrName[1:]
			}
		}
		if e.vars[arrName] != ctIntVec {
			return "", ctUnknown, fmt.Errorf("cc backend: unsupported array %s", arrName)
		}
		ic, _, err := e.emitExpr(x.Index)
		if err != nil {
			return "", ctUnknown, err
		}
		return fmt.Sprintf("%s.data[%s]", cIdent(arrName), ic), ctInt, nil

	case *HashAccessExpr:
		ve, ok := x.Hash.(*VarExpr)
		if !ok {
			return "", ctUnknown, fmt.Errorf("cc backend: non-var hash")
		}
		hName := ve.Name
		if _, has := e.vars[hName]; !has && strings.HasPrefix(hName, "$") {
			if e.vars["%"+hName[1:]] == ctIntMap {
				hName = "%" + hName[1:]
			}
		}
		if e.vars[hName] != ctIntMap {
			return "", ctUnknown, fmt.Errorf("cc backend: unsupported hash %s", hName)
		}
		kc, kt, err := e.emitExpr(x.Key)
		if err != nil || kt != ctInt {
			return "", ctUnknown, fmt.Errorf("cc backend: non-int hash key")
		}
		return fmt.Sprintf("rp_imap_get(&%s, %s)", cIdent(hName), kc), ctInt, nil

	case *MethodCallExpr:
		tc, tt, err := e.emitExpr(x.Target)
		if err != nil {
			return "", ctUnknown, err
		}
		switch x.Method {
		case "chars", "length":
			if tt == ctStr {
				return fmt.Sprintf("((int64_t)(%s.len))", tc), ctInt, nil
			}
		case "elems":
			if tt == ctIntVec || tt == ctIntMap {
				return fmt.Sprintf("((int64_t)(%s.len))", tc), ctInt, nil
			}
		case "sort":
			if tt == ctIntVec && len(x.Args) == 0 {
				return fmt.Sprintf("rp_ivec_sort(%s)", tc), ctIntVec, nil
			}
		case "sum":
			if tt == ctIntVec && len(x.Args) == 0 {
				return fmt.Sprintf("rp_ivec_sum(%s)", tc), ctInt, nil
			}
		}

	case *CallExpr:
		cv, ok := x.Callee.(*VarExpr)
		if !ok {
			return "", ctUnknown, fmt.Errorf("cc backend: dynamic call unsupported")
		}
		switch cv.Name {
		case "push":
			if len(x.Args) == 2 {
				av, okA := x.Args[0].(*VarExpr)
				if okA && e.vars[av.Name] == ctIntVec {
					vc, vt, err := e.emitExpr(x.Args[1])
					if err == nil && vt == ctInt {
						return fmt.Sprintf("(rp_ivec_push(&%s, %s), (int64_t)%s.len)", cIdent(av.Name), vc, cIdent(av.Name)), ctInt, nil
					}
				}
			}
		case "elems":
			if len(x.Args) == 1 {
				ac, at, err := e.emitExpr(x.Args[0])
				if err == nil && (at == ctIntVec || at == ctIntMap) {
					return fmt.Sprintf("((int64_t)(%s.len))", ac), ctInt, nil
				}
			}
		case "chars", "length":
			if len(x.Args) == 1 {
				ac, at, err := e.emitExpr(x.Args[0])
				if err == nil && at == ctStr {
					return fmt.Sprintf("((int64_t)(%s.len))", ac), ctInt, nil
				}
			}
		case "sum", "∑", "simd_sum":
			if len(x.Args) == 1 {
				ac, at, err := e.emitExpr(x.Args[0])
				if err == nil && at == ctIntVec {
					return fmt.Sprintf("rp_ivec_sum(%s)", ac), ctInt, nil
				}
			}
		case "sort":
			if len(x.Args) == 1 {
				ac, at, err := e.emitExpr(x.Args[0])
				if err == nil && at == ctIntVec {
					return fmt.Sprintf("rp_ivec_sort(%s)", ac), ctIntVec, nil
				}
			}
		case "abs":
			if len(x.Args) == 1 {
				ac, at, err := e.emitExpr(x.Args[0])
				if err == nil {
					if at == ctFloat {
						return fmt.Sprintf("fabs(%s)", ac), ctFloat, nil
					}
					return fmt.Sprintf("llabs(%s)", ac), ctInt, nil
				}
			}
		case "sqrt":
			if len(x.Args) == 1 {
				ac, _, err := e.emitExpr(x.Args[0])
				if err == nil {
					return fmt.Sprintf("sqrt((double)(%s))", ac), ctFloat, nil
				}
			}
		}
		if rt, exists := e.subTypes[cv.Name]; exists {
			var cArgs []string
			for _, a := range x.Args {
				ac, _, err := e.emitExpr(a)
				if err != nil {
					return "", ctUnknown, err
				}
				cArgs = append(cArgs, ac)
			}
			return fmt.Sprintf("rp_sub_%s(%s)", cIdent(cv.Name), strings.Join(cArgs, ", ")), rt, nil
		}
	}
	return "", ctUnknown, fmt.Errorf("cc backend: unsupported expr %T", ex)
}
